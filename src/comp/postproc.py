"""Постобработка масок гари (SPEC-19).

Разбор ошибок показал, где теряется IoU: не на путанице между степенями
поражения (там доля правильных 87–93 %), а на ложной гари посреди фона. Фон
занимает 91 % пикселей, поэтому ошибиться на 4.3 % фона — значит добавить
ложной площади в 43 % от настоящей гари.

Эта ложная площадь рассыпана мелкими пятнами: настоящая гарь связна и велика.
Выбрасывание пятен мельче порога даёт +0.027 IoU_burn на бустинге и проверено
независимо на сети.

Проверено и отвергнуто: латание дыр внутри гари (0.4947 против 0.4973) и
морфологическое закрытие (0.4829). Дыра в гари — чаще уцелевший островок, чем
артефакт, и закрашивать её значит врать.
"""

from __future__ import annotations

import numpy as np
from scipy.ndimage import label

# Оптимум широкий: 50…200 пикселей дают одно и то же с точностью до третьего
# знака, после 400 фильтр начинает выедать настоящие мелкие гари.
MIN_BLOB = 100


def drop_small(pred: np.ndarray, min_px: int = MIN_BLOB) -> np.ndarray:
    """Убирает связные области гари мельче `min_px` пикселей.

    Связность считается по маске «гарь / не гарь», а не по каждому классу
    отдельно: пятно из смежных классов 2 и 3 — это один пожар, и разваливать
    его на части значит потерять оба.
    """
    if min_px <= 0:
        return pred
    marks, count = label(pred > 0)
    if not count:
        return pred
    sizes = np.bincount(marks.reshape(-1))
    small = np.flatnonzero(sizes < min_px)
    if not small.size:
        return pred
    out = pred.copy()
    out[np.isin(marks, small)] = 0
    return out
